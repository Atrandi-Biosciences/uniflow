#!/usr/bin/env python3
"""Compute per-caller and cross-caller consensus metrics from the per-sample
variants parquet generated by VCF_TO_PARQUET

The parquet is a strict superset of the merged consensus VCF's per-caller
signal (one row per (sample, caller, variant) where the caller contributed
FORMAT/DP > 0), so grouping by (chrom, pos, ref, alt) and counting distinct
contributing callers is equivalent to INFO/NCALLERS — no VCF re-read needed.

Output is a flat metrics YAML compatible with the previous script
bin/lib/metrics/metrics.py

MetricsRecord stores metrics as a flat Dict[str, Any]

nested values are dropped by MetricsCollector.generate_df

The optional 4th argument is the per-cell raw_variants.parquet; when given, its
per-site cell-support counts are summarised into consensus.* metrics
that complement caller agreement with an abundance (how many cells vote for
the ALT).

Usage:
    variants_to_metrics_parquet.py <variants.parquet> <sample_name> <output.yaml> [raw_variants.parquet]
"""

import sys

import polars as pl
from lib.common_const import LibraryType, Modality
from lib.metrics.metrics import MetricsRecord

# Absolute (not relative to the active caller count) — documented in §4.9.
NCALLERS_HIGH_CONFIDENCE = 2

# A site is "multicell-supported" when at least this many distinct cells vote for
# the ALT:
MULTICELL_SUPPORT_MIN = 2

CELLS_SUPPORTING_ALT = "cells_supporting_alt"
CELLS_TOTAL_AT_SITE = "cells_total_at_site"
SITE_KEY = ["feature", "pos_local_0based", "ref", "alt"]


def cell_support_aggregates(raw_path: str) -> dict:
    """Per-site cell-support summary from the per-cell raw_variants.parquet.

    The cell-support counts are broadcast across an allele's per-cell rows, so the
    frame is deduped to one row per site (feature, pos_local, ref, alt) before
    aggregating. An empty / support-free parquet yields zeros and null medians so
    the metric keys stay present and shaped.
    """
    empty = {
        "cell_support_sites": 0,
        "median_cells_supporting_alt": None,
        "multicell_support_count": 0,
        "singlecell_support_count": 0,
        "fraction_multicell_support": None,
    }
    raw = pl.read_parquet(raw_path)
    if CELLS_SUPPORTING_ALT not in raw.columns:
        return empty

    sites = (
        raw.filter(pl.col(CELLS_SUPPORTING_ALT).is_not_null())
        .unique(subset=SITE_KEY)
        .select([*SITE_KEY, CELLS_SUPPORTING_ALT, CELLS_TOTAL_AT_SITE])
    )
    n = sites.height
    if n == 0:
        return empty

    multicell = sites.filter(
        pl.col(CELLS_SUPPORTING_ALT) >= MULTICELL_SUPPORT_MIN
    ).height
    singlecell = sites.filter(pl.col(CELLS_SUPPORTING_ALT) == 1).height
    return {
        "cell_support_sites": n,
        "median_cells_supporting_alt": sites.get_column(CELLS_SUPPORTING_ALT).median(),
        "multicell_support_count": multicell,
        "singlecell_support_count": singlecell,
        "fraction_multicell_support": multicell / n,
    }


def per_caller_aggregates(caller_df: pl.DataFrame) -> dict:
    """Per-caller numerical aggregates from the long parquet rows for one caller."""
    if caller_df.is_empty():
        return {
            "snv_count": 0,
            "mean_dp": None,
            "median_dp": None,
            "mean_vaf": None,
            "median_vaf": None,
            "het_count": 0,
            "hom_count": 0,
        }
    return caller_df.select(
        snv_count=pl.len(),
        mean_dp=pl.col("dp").mean(),
        median_dp=pl.col("dp").median(),
        mean_vaf=pl.col("af").mean(),
        median_vaf=pl.col("af").median(),
        het_count=((pl.col("af") > 0.05) & (pl.col("af") < 0.8)).sum(),
        hom_count=(pl.col("af") >= 0.8).sum(),
    ).row(0, named=True)


def main():
    parquet_path = sys.argv[1]
    sample_name = sys.argv[2]
    out_path = sys.argv[3]

    # Limit the scope of metrics to SNV only
    df = pl.read_parquet(parquet_path).filter(pl.col("type") == "SNV")

    record = MetricsRecord(
        source_id=sample_name,
        library_type=LibraryType.DNA,
        modality=Modality.VARIANTS,
    )

    callers = df.get_column("caller").unique().sort().to_list() if df.height else []

    for caller in callers:
        caller_df = df.filter(pl.col("caller") == caller)
        for key, value in per_caller_aggregates(caller_df).items():
            record.add(f"{caller}.{key}", value)

    site_callers = df.group_by(["chrom", "pos", "ref", "alt"]).agg(
        ncallers=pl.col("caller").n_unique()
    )
    total_sites = site_callers.height
    high_conf = site_callers.filter(
        pl.col("ncallers") >= NCALLERS_HIGH_CONFIDENCE
    ).height
    singletons = site_callers.filter(pl.col("ncallers") == 1).height

    record.add("consensus.total_sites", total_sites)
    record.add("consensus.high_confidence_count", high_conf)
    record.add("consensus.singleton_count", singletons)
    record.add(
        "consensus.fraction_high_confidence",
        (high_conf / total_sites) if total_sites > 0 else None,
    )

    singleton_sites = site_callers.filter(pl.col("ncallers") == 1).select(
        ["chrom", "pos", "ref", "alt"]
    )
    singleton_per_caller = (
        df.join(singleton_sites, on=["chrom", "pos", "ref", "alt"], how="inner")
        .group_by("caller")
        .agg(singleton_count=pl.len())
    )
    singleton_map = dict(
        zip(
            singleton_per_caller.get_column("caller").to_list(),
            singleton_per_caller.get_column("singleton_count").to_list(),
        )
    )
    for caller in callers:
        record.add(f"{caller}.singleton_count", singleton_map.get(caller, 0))

    # Per-cell-support summary, when the raw_variants.parquet is supplied.
    if len(sys.argv) > 4:
        for key, value in cell_support_aggregates(sys.argv[4]).items():
            record.add(f"consensus.{key}", value)

    record.write_records(out_path)


if __name__ == "__main__":
    main()
